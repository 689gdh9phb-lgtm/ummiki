export interface NameGroup {
  id: string // например «1-10»
  start: number
  end: number
  title: string
  names: DivineName[]
}

export const nameGroups: NameGroup[] = Array.from({ length: 10 }, (_, i) => {
  const start = i * 10 + 1
  const end = Math.min(start + 9, 99)
  return {
    id: `${start}-${end}`,
    start,
    end,
    title: `Имена ${start}–${end}`,
    names: divineNames.filter((n) => n.id >= start && n.id <= end),
  }
})

export function getNameGroup(id: string): NameGroup | undefined {
  return nameGroups.find((g) => g.id === id)
}
